#!/usr/bin/env python3
"""Derive a traceable report from explicit run directories and independently recheck copies."""
import argparse
from collections import defaultdict
import csv
import hashlib
import json
import math
import os
from pathlib import Path
import re
import shlex
import statistics as st
import subprocess

ROOT = Path(__file__).resolve().parents[2]
SOURCES = {}


def read(path):
    path = Path(path)
    raw = path.read_bytes()
    SOURCES[str(path)] = hashlib.sha256(raw).hexdigest()
    return json.loads(raw)


def table(lines, heads, rows):
    lines += ["| "+" | ".join(heads)+" |", "|"+"---|"*len(heads)]
    lines += ["| "+" | ".join(map(str,row))+" |" for row in rows]
    lines.append("")


def groups(rows, fields):
    ans = defaultdict(list)
    for r in rows:
        ans[tuple(r[k] for k in fields)].append(r)
    return ans


def duration(item, key):
    value = item.get(key,{"start":0,"end":0})
    return (value["end"]-value["start"])/1e6


def main():
    p = argparse.ArgumentParser()
    for name in ("graph","perf","sam","scale","torch","dp","datalog","buckets"):
        p.add_argument("--"+name,type=Path,required=True)
    p.add_argument("--report",type=Path,default=ROOT/"sym1/baseline_report.md")
    args = p.parse_args()
    out = Path(os.environ["SYMFABRIC_RUN_DIR"])
    runs = {k:getattr(args,k).resolve() for k in ("graph","perf","sam","scale","torch","dp","datalog","buckets")}
    for name,path in runs.items():
        assert read(path/"completion.json")["exit_code"] == 0, name
    lock = read(ROOT/"sym1/upstream_lock.json")
    for row in lock["repositories"]:
        sha = subprocess.check_output(["git","-C",str(ROOT/row["path"]),"rev-parse","HEAD"],text=True).strip()
        assert sha == row["commit"], row["path"]
    metadata = read(runs["graph"]/"metadata.json")
    host = subprocess.check_output(["lscpu","-J"],text=True)
    (out/"lscpu.json").write_text(host)
    assert json.loads((out/"lscpu.json").read_text()) == json.loads(host)
    package_versions = subprocess.check_output([str(ROOT/"sym1/.venv/bin/python"),"-m","pip","freeze"],text=True)
    (out/"packages.txt").write_text(package_versions)
    results = {"run_directories":{k:str(v) for k,v in runs.items()}}
    lines = ["# sym1 local baseline and bottleneck report", "",
             "This report is generated by `scripts/report_baselines.py` from explicit raw-run directories. "
             "CPU times are measured on this host; simulated cycles are measurements of upstream models, not silicon. "
             "All ratios are derived with the formulas below. No GPU or sym1 accelerator speedup is claimed.", "",
             "## Conditions and correctness", "",
             f"Measured runner affinity: `{metadata['cpu_affinity']}`; configured address-space ceiling: "
             f"`{metadata['address_space_limit_bytes']}` bytes. Compute experiments were run sequentially. "
             "The host was not reserved against other users; medians and raw ranges are retained. "
             "Host details and package versions are saved beside this report's analysis JSON.", ""]
    datasets = []
    for name in ("ca-GrQc","email-Enron","roadNet-CA"):
        meta = read(ROOT/f"sym1/data/{name}.json")
        for suffix,field in (("el","sha256_el"),("txt.gz","sha256_gz")):
            assert hashlib.sha256((ROOT/f"sym1/data/{name}.{suffix}").read_bytes()).hexdigest() == meta[field]
        datasets.append(meta)
    results["datasets"] = datasets
    table(lines,["Dataset","Vertices (measured)","Undirected edges (measured)","Maximum degree (measured)"],
          [(r["name"],r["nodes"],r["undirected_edges"],r["max_degree"]) for r in datasets])
    lines += ["Inputs are public SNAP graphs, normalized by removing self-loops, deduplicating undirected edges and compacting vertex IDs. "
              "Vertices appearing only in discarded loops are absent. SSSP uses GAPBS's deterministic generated weights, not geographical road distances. "
              "Source IDs are chosen by maximum degree. This is a diagnostic graph suite, not a reproduction of the complete GAP evaluation dataset suite.", ""]
    graph = read(runs["graph"]/"graph.json")
    assert all(r["pass"] for r in graph)
    graph_summary = []
    for r in graph:
        raw = Path(r["log"]).read_text()
        assert [float(x) for x in re.findall(r"Trial Time:\s+([0-9.]+)",raw)] == r["trial_s"]
        assert raw.count("PASS") == r["verified_trials"]
    for key,rs in groups(graph,["dataset","kernel"]).items():
        times = {r["threads"]:st.median(r["trial_s"]) for r in rs}
        graph_summary.append(dict(dataset=key[0],kernel=key[1],median_s=times,
                                  speedup_32=times[1]/times[32],range_s={r["threads"]:[min(r["trial_s"]),max(r["trial_s"])] for r in rs}))
    results["graph"] = graph_summary
    lines += [f"GAPBS: measured {len(graph)} configurations, {sum(r['verified_trials'] for r in graph)} verified trials. "
              "The upstream BFS, Dijkstra and set-intersection verifiers are separate algorithms from the measured kernels.", "",
              "## CPU graph kernels", "", "Kernel-only median milliseconds; graph construction, verification and process startup are excluded. "
              "Derived speedup = one-thread median / corresponding parallel median; below unity means slower.", ""]
    table(lines,["Dataset","Kernel","1 thread ms","8 threads ms","32 threads ms","32-thread speedup"],
          [(r["dataset"],r["kernel"],*[f"{r['median_s'][t]*1000:.3f}" for t in (1,8,32)],f"{r['speedup_32']:.3f}x") for r in graph_summary])
    perf_rows = []
    for r in read(runs["perf"]/"perf.json"):
        counters = {}
        with Path(r["counters"]).open() as f:
            for fields in csv.reader(line for line in f if line.strip() and not line.startswith("#")):
                counters[fields[2]] = float(fields[0])
        report = Path(r["report"]).read_text()
        gomp = sum(float(m[0]) for m in re.findall(r"^\s*([0-9.]+)%\s+\S+\s+(libgomp\S*)\s+",report,re.M))
        perf_rows.append(dict(**r,ipc=counters["instructions:u"]/counters["cycles:u"],
                              displayed_libgomp_cycle_pct_lower_bound=gomp,counter_values=counters))
    results["perf"] = perf_rows
    table(lines,["Dataset/kernel","Threads","IPC (derived)","libgomp cycle-sample share (lower bound)"],
          [(r["dataset"]+"/"+r["kernel"],r["threads"],f"{r['ipc']:.3f}",f"{r['displayed_libgomp_cycle_pct_lower_bound']:.2f}%") for r in perf_rows])
    for label,start,end in (("lock", "0x1d720", "0x1d780"),("wait","0x1e000","0x1e060")):
        disasm = subprocess.check_output(["objdump","-d",f"--start-address={start}",f"--stop-address={end}","/lib64/libgomp.so.1"],text=True)
        (out/f"libgomp-{label}.txt").write_text(disasm)
        assert "pause" in (out/f"libgomp-{label}.txt").read_text()
    lines += ["The CPU samples include graph loading and all benchmark iterations but exclude the verifier. "
              "libgomp shares sum only displayed symbols, so they are lower bounds, not exact total shares. "
              "Disassembly of the hot addresses shows polling loops containing `pause`; GAPBS `sssp.cc` explicitly uses critical sections and barriers per bucket iteration. "
              "Together with thread scaling, this establishes synchronization/spin overhead in this SSSP configuration. "
              "The host is shared: co-tenant preemption can amplify barrier waiting, so this does not isolate an intrinsic hardware-independent scaling ceiling. "
              "Generic cache-miss counters include all counted accesses and do not measure DRAM bandwidth saturation.", ""]
    buckets = read(runs["buckets"]/"buckets.json")
    assert all(r["pass_check"] for r in buckets)
    bsummary = []
    for key,rs in groups(buckets,["delta","threads"]).items():
        timing = next(r for r in rs if not r["diagnostic"])
        diag = next(r for r in rs if r["diagnostic"])
        counts = [int(x[1]) for x in diag["steps"]]
        assert len(counts) == diag["iteration_counts"][0]
        assert [float(x) for x in re.findall(r"Trial Time:\s+([0-9.]+)",Path(timing["log"]).read_text())] == timing["trial_s"]
        bsummary.append(dict(delta=key[0],threads=key[1],median_s=st.median(timing["trial_s"]),
                             range_s=[min(timing["trial_s"]),max(timing["trial_s"])],iterations=len(counts),
                             median_frontier=st.median(counts),max_frontier=max(counts)))
    results["buckets"] = bsummary
    lines += ["### Bucket-width sensitivity", "", "Measured on the same road graph, source and generated weights. "
              "Timing runs are separate from logged frontier runs; every output passes upstream serial Dijkstra. "
              "Changing bucket width changes scheduling/work and is a software parameter effect, not a hardware gain.", ""]
    table(lines,["Delta","Threads","Median kernel ms [min,max]","Iterations (diagnostic)","Median frontier (diagnostic)"],
          [(r["delta"],r["threads"],f"{r['median_s']*1000:.3f} [{r['range_s'][0]*1000:.3f},{r['range_s'][1]*1000:.3f}]",
            r["iterations"],f"{r['median_frontier']:.1f}") for r in bsummary])
    lines += ["The bucket sweep has substantial shared-host timing variation, including drift against the initial baseline. "
              "Do not treat ratios across these runs as a clean causal speedup. Iteration/frontier counts and verified outputs are still valid structural evidence. "
              "An isolated-host or randomized/interleaved experiment is needed for a publishable bucket-tuning latency comparison.", ""]
    torch_rows = read(runs["torch"]/"torch_struct.json")
    dp = read(runs["dp"]/"dp_schedule.json")
    assert all(r["pass"] for r in torch_rows) and all(r["pass_check"] for r in dp)
    dpsummary = []
    for key,rs in groups(dp,["states","batch","semiring","threads"]).items():
        times = {method:st.median([t for r in rs for t in r["wall_s"][method]]) for method in ("matrix_scan","vector_recurrence")}
        dpsummary.append(dict(states=key[0],batch=key[1],semiring=key[2],threads=key[3],median_s=times,
                              scan_over_vector=times["matrix_scan"]/times["vector_recurrence"]))
    results["dp"] = dpsummary
    lines += ["## CPU semiring DP", "", f"Measured {len(torch_rows)} initial Torch-Struct cases and {len(dp)} paired schedule cases; "
              "all pass an independent float64 NumPy recurrence with the explicitly recorded floating-point tolerance. "
              "Potentials are synthetic, inference-only, with no task training or accuracy claim. "
              "Below: pooled median of timed trials across seeds; the methods see identical input tensors and have shuffled execution order.", ""]
    table(lines,["States","Batch","Semiring","Threads","Matrix scan ms","Vector recurrence ms","Scan / vector"],
          [(r["states"],r["batch"],r["semiring"],r["threads"],f"{r['median_s']['matrix_scan']*1000:.3f}",
            f"{r['median_s']['vector_recurrence']*1000:.3f}",f"{r['scan_over_vector']:.3f}x") for r in dpsummary])
    prof_summary = []
    for mode in ("log","max"):
        for method in ("matrix_scan","vector_recurrence"):
            es = read(runs["dp"]/f"profile-{mode}-{method}.json")
            total = sum(e["self_cpu_time_us"] for e in es)
            top = sorted(es,key=lambda e:e["self_cpu_time_us"],reverse=True)[:4]
            prof_summary.append(dict(semiring=mode,method=method,self_cpu_us=total,
                                     positive_self_alloc_bytes=sum(max(0,e["self_cpu_memory_bytes"]) for e in es),
                                     top=[dict(key=e["key"],self_cpu_pct=e["self_cpu_time_us"]/total*100) for e in top]))
    results["dp_profiles"] = prof_summary
    table(lines,["Semiring / method","Positive operator allocation MB","Top self-time operators"],
          [(r["semiring"]+" / "+r["method"],f"{r['positive_self_alloc_bytes']/1e6:.3f}",
            "; ".join(f"{e['key']} {e['self_cpu_pct']:.1f}%" for e in r["top"])) for r in prof_summary])
    lines += ["Profile configuration is recorded in `baseline_dp_schedule.py`. Positive allocation totals are the sum of positive "
              "operator self-memory deltas, not peak resident memory or measured DRAM traffic. Self-time shares are exclusive; nested inclusive durations are not summed. "
              "Upstream `LinearChain.logpartition` combines state-transition matrices in a tree; log/max semiring matmul broadcasts a state cube before reduction. "
              "The vector recurrence eliminates that extra state dimension at the cost of sequential dependence across positions. "
              "Its measured CPU advantage is an algorithm/schedule result, not evidence of a sym1 accelerator speedup.", ""]
    datalog = read(runs["datalog"]/"datalog.json")
    assert all(r["pass_check"] for r in datalog)
    drows = []
    for r in datalog:
        prog = read(r["profile"])["root"]["program"]
        rel = prog["relation"]["reach"]
        iters = list(rel.get("iteration",{}).values())
        assert rel["num-tuples"]+sum(it["num-tuples"] for it in iters) == r["output_tuples"]
        nonrec = duration(rel,"runtime")
        recursive = sum(duration(it,"runtime") for it in iters)
        copy = sum(duration(it,"copytime") for it in iters)
        drows.append(dict(dataset=r["dataset"],seed=r["seed"],queries=r["queries"],threads=r["threads"],
                          output_tuples=r["output_tuples"],wall_s=r["wall_s"],iterations=len(iters),
                          program_s=duration(prog,"runtime"),nonrec_s=nonrec,recursive_s=recursive,copy_s=copy,
                          evaluation_s=nonrec+recursive+copy,
                          load_s=sum(duration(v,"loadtime") for v in prog["relation"].values()),save_s=duration(rel,"savetime")))
    for r in (datalog[0],datalog[len(datalog)//2],datalog[-1]):
        with (Path(r["profile"]).parent/"reach.csv").open() as f:
            assert sum(1 for line in f) == r["output_tuples"]
    dsumm = []
    for key,rs in groups(drows,["dataset","seed","queries","threads"]).items():
        dsumm.append(dict(dataset=key[0],seed=key[1],queries=key[2],threads=key[3],
                          **{k:st.median(r[k] for r in rs) for k in ("output_tuples","wall_s","iterations","program_s","recursive_s","copy_s","evaluation_s","load_s","save_s")},
                          evaluation_range_s=[min(r["evaluation_s"] for r in rs),max(r["evaluation_s"] for r in rs)]))
    results["datalog"] = dsumm
    lines += ["## Compiled CPU Datalog", "", f"Measured {len(datalog)} executions, with complete result sets checked against independent deque BFS. "
              "Each query includes its source in reachability. Sources share the input graph but remain separate query keys. "
              "Times below are medians of repeated executions at each seed/configuration. Evaluation = nonrecursive + recursive iteration + copy/merge durations "
              "from Souffle's microsecond profiler, matching `profile/Relation.h`; input loading and output saving are separate. "
              "Recursive timing also includes generated index lookups, duplicate checks and runtime overhead, not just successful joins.", ""]
    table(lines,["Dataset","Seed","Q","Threads","Eval ms [min,max]","Recursive ms","Copy ms","Load+save ms"],
          [(r["dataset"],r["seed"],r["queries"],r["threads"],
            f"{r['evaluation_s']*1000:.2f} [{r['evaluation_range_s'][0]*1000:.2f},{r['evaluation_range_s'][1]*1000:.2f}]",
            f"{r['recursive_s']*1000:.2f}",f"{r['copy_s']*1000:.2f}",f"{(r['load_s']+r['save_s'])*1000:.2f}") for r in dsumm])
    lines += ["Thread scaling depends on query count, seed and runtime variability. These measurements do not support a universal claim "
              "that relation copying dominates every Datalog run; recursive work and small-task overhead must be accounted separately. "
              "The program is bounded source reachability, not all-pairs transitive closure or a program-analysis benchmark.", ""]
    sam = read(runs["sam"]/"sam.json")
    assert all(r["pass"] and r["matches"] == r["stats"]["multiply"]["cycle_operation"] for r in sam)
    # Recheck every recorded intersection cardinality directly against the normalized input graph.
    for name in (r["name"] for r in datasets):
        adj = defaultdict(set)
        with (ROOT/f"sym1/data/{name}.el").open() as f:
            for line in f:
                u,v = map(int,line.split()); adj[u].add(v); adj[v].add(u)
        for r in (r for r in sam if r["dataset"] == name):
            assert len(adj[r["u"]]&adj[r["v"]]) == r["matches"]
        del adj
    ssumm = []
    for key,rs in groups(sam,["dataset","sample"]).items():
        variants = groups(rs,["depth","skip"])
        base = variants[2,False]
        cyc = sum(r["cycles"] for r in base)
        ssumm.append(dict(dataset=key[0],sample=key[1],cases=len(base),base_cycles=cyc,
                          mac_active_pct=sum(r["matches"] for r in base)/cyc*100,
                          cycles_per_case=cyc/len(base),
                          deeper_fifo_speedup=cyc/sum(r["cycles"] for r in variants[16,False]),
                          skip_speedup=cyc/sum(r["cycles"] for r in variants[2,True])))
    results["sam"] = ssumm
    lines += ["## Sparse streaming simulator", "", f"Measured {len(sam)} upstream SAM primitive-model cases with backpressure enabled. "
              "Every output coordinate list and scalar reduction passed the independent golden during execution; this report independently rechecks all intersection cardinalities. "
              "The hub sample is intentionally biased and repeated across seeds, not an independent population sample. "
              "MAC active share = matched values / full pipeline cycles; speedups use sums over paired cases, not an average of per-case speedups.", ""]
    table(lines,["Graph","Sample","Cases in base variant","Mean cycles","MAC active","FIFO-depth speedup","Skip speedup"],
          [(r["dataset"],r["sample"],r["cases"],f"{r['cycles_per_case']:.2f}",f"{r['mac_active_pct']:.2f}%",f"{r['deeper_fifo_speedup']:.3f}x",f"{r['skip_speedup']:.3f}x") for r in ssumm])
    lines += ["This isolates coordinate scanning/intersection and token fill/drain. The resident array blocks do not model DRAM bandwidth. "
              "FIFO and skip experiments test different mechanisms: deeper buffering does not eliminate coordinate comparisons or create matches. "
              "Summed isolated dot-product cycles are not full triangle-count latency, since cross-fiber overlap and graph scheduling are absent.", ""]
    scale = read(runs["scale"]/"scale.json")
    scsummary = []
    for r in scale:
        with Path(r["report"]).open() as f:
            original = list(csv.DictReader(f,skipinitialspace=True))[int(r["raw"]["LayerID"])]
        assert original == r["raw"]
        cycles = float(original["Total Cycles"])
        total = float(original["Total Cycles (incl. prefetch)"])
        util = r["M"]*r["N"]*r["K"]/(cycles*r["array"]**2)*100
        assert math.isclose(util,float(original["Overall Util %"]),rel_tol=1e-12)
        scsummary.append(dict(array=r["array"],mode=r["mode"],M=r["M"],N=r["N"],K=r["K"],
                              compute_cycles=cycles,total_cycles=total,stall_cycles=float(original["Stall Cycles"]),
                              compute_window_util_pct=util,prefetch_inclusive_util_pct=util*cycles/total))
    results["scale"] = scsummary
    lines += ["## Dense systolic scheduling simulator", "", f"Measured {len(scale)} upstream SCALE-Sim scheduling cases; raw reports were reread and useful-operation utilization independently recomputed. "
              "CALC and USER retain their upstream meanings; USER uses the upstream configured bandwidth, not a calibrated physical memory system. "
              "The upstream column named Overall Util excludes prefetch in its denominator; both denominators are shown explicitly here. "
              "These are scheduling checks, not numerical validation of nonlinear semiring arithmetic.", ""]
    table(lines,["Array","Mode","M/N/K","Compute cycles","Prefetch-inclusive cycles","Stalls","Compute util","Prefetch-inclusive util"],
          [(r["array"],r["mode"],f"{r['M']}/{r['N']}/{r['K']}",int(r["compute_cycles"]),int(r["total_cycles"]),int(r["stall_cycles"]),
            f"{r['compute_window_util_pct']:.4f}%",f"{r['prefetch_inclusive_util_pct']:.4f}%") for r in scsummary])
    lines += ["Small query dimensions underfill the dense array even when the modeled compute window has no memory stalls. "
              "Larger query batches amortize pipeline overhead but are not a free single-query latency improvement. "
              "Different value-unit latency, layout, SRAM banking or off-chip traffic can change the result.", "",
              "## Interpretation and remaining evidence", "",
              "The measured bottlenecks are configuration-dependent: synchronization/priority-bucket scheduling in the profiled CPU SSSP case; "
              "matrix-scan work and temporary tensors in CPU DP; indexed recursive evaluation and small-task overhead in Datalog; "
              "coordinate/token processing in SAM; and narrow-query utilization in the dense array model. "
              "They do not establish a single universal memory bottleneck. Bucket tuning and the DP schedule ablation are software improvements and cannot be credited to sym1.", "",
              "The literature audit is in `literature_review.md`. GPU software characterization remains unavailable on this host. "
              "REASON/Revet/Capstan are not reproduced by the available generic simulators; DPU-v2 RTL, GraphLily, Ramulator and STONNE are cloned but not executed in this report. "
              "No cycle-level sym1-versus-baseline result, PE synthesis or end-to-end neuro-symbolic speedup has been obtained. "
              "The original closed-form model is kept distinct from the upstream simulator measurements.", "",
              "## Raw evidence and reproduction", "",
              f"Analysis JSON, source hashes, environment records and disassembly: `{out.relative_to(ROOT)}`.", ""]
    for name,path in runs.items():
        meta = read(path/"metadata.json")
        cmd = ["python3","sym1/scripts/run_logged.py","--threads",str(len(meta["cpu_affinity"])),name,"--"]+meta["command"]
        lines += [f"- {name}: `{path.relative_to(ROOT)}`", "", "  ```bash", "  "+shlex.join(cmd), "  ```", ""]
    results["source_sha256"] = SOURCES
    results["validation"] = "PASS"
    target = out/"analysis.json"
    target.write_text(json.dumps(results,indent=2)+"\n")
    saved = json.loads(target.read_text())
    # Mandatory independent copy checks: raw trial -> saved median, raw cycle report -> saved utilization.
    assert math.isclose(saved["graph"][0]["median_s"]["1"],st.median(graph[0]["trial_s"]))
    assert math.isclose(saved["scale"][0]["compute_window_util_pct"],float(scale[0]["raw"]["Overall Util %"]))
    assert saved["datalog"][-1]["output_tuples"] == datalog[-1]["output_tuples"]
    for source,digest in saved["source_sha256"].items():
        assert hashlib.sha256(Path(source).read_bytes()).hexdigest() == digest
    report = "\n".join(lines)+"\n"
    with args.report.open("x") as f:
        f.write(report)
    assert args.report.read_text() == report
    print(json.dumps({"validation":"PASS","report":str(args.report),"analysis":str(target),
                      "counts":{"gapbs":len(graph),"torch_struct":len(torch_rows),"paired_dp":len(dp),
                                "datalog":len(datalog),"sam":len(sam),"scale":len(scale)}}))


if __name__ == "__main__":
    main()
